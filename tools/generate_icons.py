"""Generate native Compose vectors from the shared NeoSerf SVG sources. Run with Python 3."""
from pathlib import Path
import xml.etree.ElementTree as ET

ROOT = Path(__file__).resolve().parents[1]
ICONS = {
    "ArrowBack": "back",
    "ArrowForward": "forward",
    "Home": "home",
    "Refresh": "reload",
    "MoreVert": "menu",
    "Add": "plus",
    "Close": "close",
    "BookmarkBorder": "bookmark",
    "Bookmark": "bookmark-filled",
    "Search": "search",
    "History": "history",
    "Key": "key",
    "Lock": "lock",
    "Shield": "shield",
    "Security": "shield-off",
    "Tune": "settings",
    "Visibility": "eye",
    "VisibilityOff": "eye-off",
    "MyLocation": "location",
    "Logout": "logout",
    "Password": "password",
    "Delete": "delete",
    "ContentCopy": "copy",
    "AutoFixHigh": "autofill",
    "Public": "globe",
    "CloudSync": "cloud-sync",
    "TextDecrease": "text-minus",
    "TextIncrease": "text-plus",
    "WbSunny": "sun",
    "NightsStay": "moon",
    "Cloud": "cloud",
    "BlurOn": "fog",
    "AcUnit": "snow",
    "Thunderstorm": "storm",
    "WaterDrop": "drop",
    "Device": "device"
}

def main():
    lines = [
        '// Generated by tools/generate_icons.py from desktop/assets/icons/*.svg.',
        'package com.example.ui.icons', '',
        'import androidx.compose.ui.graphics.Color',
        'import androidx.compose.ui.graphics.SolidColor',
        'import androidx.compose.ui.graphics.StrokeCap',
        'import androidx.compose.ui.graphics.StrokeJoin',
        'import androidx.compose.ui.graphics.vector.ImageVector',
        'import androidx.compose.ui.graphics.vector.PathParser',
        'import androidx.compose.ui.unit.dp', '',
        'object NeoIcons {'
    ]
    for symbol, name in ICONS.items():
        svg = ET.parse(ROOT / f'desktop/assets/icons/{name}.svg').getroot()
        path, = list(svg)
        assert svg.get('viewBox') == '0 0 24 24'
        assert path.tag.endswith('path')
        data = path.attrib['d']
        filled = 'true' if path.get('fill') == 'currentColor' else 'false'
        mirrored = 'true' if symbol in ('ArrowBack', 'ArrowForward', 'Logout') else 'false'
        width = path.get('stroke-width', '1.7')
        lines.append(f'  val {symbol}: ImageVector by lazy {{ icon("{name}", "{data}", {width}f, {filled}, {mirrored}) }}')
    lines.extend([
        '', '  private fun icon(name: String, data: String, width: Float, filled: Boolean, mirrored: Boolean): ImageVector =',
        '    ImageVector.Builder(name, 24.dp, 24.dp, 24f, 24f, autoMirror = mirrored).addPath(',
        '      pathData = PathParser().parsePathString(data).toNodes(),',
        '      fill = if (filled) SolidColor(Color.Black) else null,',
        '      stroke = SolidColor(Color.Black), strokeLineWidth = width,',
        '      strokeLineCap = StrokeCap.Round, strokeLineJoin = StrokeJoin.Round',
        '    ).build()', '}', ''
    ])
    output = ROOT / 'app/src/main/java/com/example/ui/icons/NeoIcons.kt'
    output.parent.mkdir(parents=True, exist_ok=True)
    output.write_text('\n'.join(lines), encoding='utf-8')
    resources = ['assets/logo.svg', 'assets/style.qss']
    resources += [f'assets/icons/{path.name}' for path in sorted((ROOT / 'desktop/assets/icons').glob('*.svg'))]
    (ROOT / 'desktop/resources.qrc').write_text('<RCC>\n  <qresource prefix="/">\n' +
        ''.join(f'    <file>{path}</file>\n' for path in resources) + '  </qresource>\n</RCC>\n', encoding='utf-8')
    print(f'Generated {len(ICONS)} Compose icons and Qt resource entries from shared SVGs')

if __name__ == '__main__':
    main()
